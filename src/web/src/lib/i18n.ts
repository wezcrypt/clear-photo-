export const dictionaries = { en, ar };
export type Locale = keyof typeof dictionaries;

export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[locale][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const I18nContext = createContext<{ locale: Locale; t: (k: Key, v?: Record<string, string | number>) => string; setLocale: (l: Locale) => void }>({
  locale: 'en',
  t: (k, v) => translate('en', k, v),
  setLocale: () => undefined,
});

export function useT() {
  return useContext(I18nContext);
}

export function errorText(t: (k: Key) => string, e: unknown): string {
  const code = (e as { code?: string })?.code;
  if (code && (`err_${code}` as Key) in en) return t(`err_${code}` as Key);
  if (e instanceof TypeError) return t('err_network');
  return t('err_generic');
}
